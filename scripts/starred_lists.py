"""Generate deterministic language and topic indexes from GitHub stars.

The GitHub GraphQL response is treated as untrusted input. Both Markdown files
are rendered from one pagination pass and staged completely before either
destination is replaced. If the second replacement fails, the first output is
restored to its exact pre-call bytes and mode unless an external writer changed
it, in which case rollback fails closed without overwriting that newer content.
"""

